const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'air-ops-test-'));
process.env.DATA_DIR=tmp;
process.env.APP_SECRET='test-only-secret-key-not-for-production';
process.env.AUTO_UPDATE_MIN='0';
const netguard=require('../src/netguard');
netguard.assertPublicUrl=async raw=>{ if(!raw.startsWith('https://example.org/')) throw Error('Blocked by test public URL policy'); };
const app=require('../src/server');
const {db}=require('../src/db');
const originalFetch=global.fetch;
let outboundCount=0;
let lastOutbound=null;
global.fetch=(url,opts)=>{
 if(String(url).startsWith('https://example.org/')){
   outboundCount++;lastOutbound={url,opts};
   return Promise.resolve({ok:true,status:201,json:async()=>({id:'remote-91'})});
 }
 return originalFetch(url,opts);
};
test('operations key scope, inbound events, ticket idempotency, outbound and revocation',async t=>{
 const server=app.listen(0,'127.0.0.1');
 await new Promise(done=>server.once('listening',done));
 t.after(async()=>{
  await new Promise(done=>server.close(done));
  global.fetch=originalFetch;
  db.close();fs.rmSync(tmp,{recursive:true,force:true});
 });
 const base='http://127.0.0.1:'+server.address().port;
 const request=async(method,url,body,headers={})=>{
  const r=await fetch(base+url,{method,headers:{...(body?{'content-type':'application/json'}:{}),...headers},body:body?JSON.stringify(body):undefined});
  return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')};
 };
 const user=await request('POST','/api/signup',{email:'test@example.com',password:'strong-test-password'});
 assert.equal(user.status,200);
 const cookie={Cookie:user.cookie.split(';')[0]};
 const noAuth=await request('POST','/api/operations/keys',{name:'external',scopes:['events:write']});
 assert.equal(noAuth.status,401);
 const readKey=await request('POST','/api/operations/keys',{name:'events',scopes:['events:write'],expires_in_days:5},cookie);
 assert.equal(readKey.status,201);
 assert.match(readKey.data.token,/^air_live_/);
 assert.equal(db.prepare('SELECT token_hash FROM ops_api_keys WHERE id=?').get(readKey.data.id).token_hash.includes(readKey.data.token),false);
 const evHeaders={Authorization:'Bearer '+readKey.data.token};
 const event=await request('POST','/api/v1/events',{source:'whatsapp',source_id:'m-1',type:'message',message:'Please check scanner'},evHeaders);
 assert.equal(event.status,202);assert.ok(event.data.id);
 const dup=await request('POST','/api/v1/events',{source:'whatsapp',source_id:'m-1',message:'Please check scanner'},evHeaders);
 assert.equal(dup.data.id,event.data.id);assert.equal(dup.data.duplicate,true);
 const blocked=await request('POST','/api/v1/events',{source:'whatsapp',source_id:'m-2',message:'Please open',open_ticket:true},evHeaders);
 assert.equal(blocked.status,403);
 const listBlocked=await request('GET','/api/v1/tickets',null,evHeaders);
 assert.equal(listBlocked.status,403);
 const cfg=await request('POST','/api/operations/integrations',{name:'Helpdesk',provider:'webhook',endpoint:'https://example.org/tickets',api_key:'EXAMPLE-TEST-KEY-12345'},cookie);
 assert.equal(cfg.status,201);assert.equal(cfg.data.provider,'webhook');
 assert.equal(JSON.stringify(cfg.data).includes('EXAMPLE-TEST-KEY'),false);
 const allCfg=await request('GET','/api/operations/integrations',null,cookie);
 assert.equal(JSON.stringify(allCfg.data).includes('EXAMPLE-TEST-KEY'),false);
 const writeKey=await request('POST','/api/operations/keys',{name:'ticket bot',scopes:['tickets:read','tickets:write','events:write']},cookie);
 const h={Authorization:'Bearer '+writeKey.data.token,'Idempotency-Key':'unique-7d151cad'};
 const ticket=await request('POST','/api/v1/tickets',{title:'Scanner broken',description:'Store needs repair',priority:3},h);
 assert.equal(ticket.status,201);
 assert.equal(ticket.data.status,'sent');
 assert.equal(ticket.data.external_id,'remote-91');
 assert.equal(outboundCount,1);
 assert.equal(lastOutbound.opts.headers.Authorization,'Bearer EXAMPLE-TEST-KEY-12345');
 const again=await request('POST','/api/v1/tickets',{title:'Ignore duplicate',description:'Ignore'},h);
 assert.equal(again.data.id,ticket.data.id);assert.equal(outboundCount,1);
 const get=await request('GET','/api/v1/tickets/'+ticket.data.id,null,h);
 assert.equal(get.data.title,'Scanner broken');
 const eventsTicket=await request('POST','/api/v1/events',{source:'whatsapp',source_id:'m-3',message:'Broken printer',open_ticket:true,title:'Printer repair'},h);
 assert.equal(eventsTicket.status,202);assert.equal(eventsTicket.data.ticket.status,'sent');
 const operations=require('../src/operations');
 const otherKey=operations.createKey('u999',{name:'isolated-tenant',scopes:['tickets:read']});
 const isolated=await request('GET','/api/v1/tickets',null,{Authorization:'Bearer '+otherKey.token});
 assert.equal(isolated.status,200);
 assert.equal(isolated.data.length,0);
 const actions=require('../src/actions');
 const outsider={isOwner:false,sessionId:'u1',settings:{options:{act_ticket:'anyone'}}};
 assert.equal(actions.toolsFor(outsider).some(x=>x.function.name==='create_ticket'),false);
 assert.match(await actions.execute('create_ticket',{title:'No',description:'No'},outsider),/restricted/);
 const revoked=await request('DELETE','/api/operations/keys/'+writeKey.data.id,null,cookie);
 assert.equal(revoked.status,200);
 const after=await request('GET','/api/v1/tickets',null,h);
 assert.equal(after.status,401);
});
